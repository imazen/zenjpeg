/// Verify all configurations produce expected hashes.
/// This test is skipped until hashes are populated.
#[test]
fn test_frymire_hashes_locked() {
    if EXPECTED_HASHES.is_empty() {
        println!("No hashes configured yet. Run print_all_hashes to generate.");
        return;
    }

    let (rgb, width, height) = load_frymire();

    for (config_name, quality, expected_hash) in EXPECTED_HASHES {
        let config = test_configs()
            .into_iter()
            .find(|c| c.name == *config_name)
            .expect("Unknown config");

        let jpeg = config.encode(&rgb, width, height, *quality as f32);
        let actual_hash = sha256_hex(&jpeg);

        assert_eq!(
            actual_hash, *expected_hash,
            "{} Q{}: hash mismatch!\n  expected: {}\n  actual:   {}\n  size: {} bytes",
            config_name, quality, expected_hash, actual_hash, jpeg.len()
        );
    }
}

/// Test that both backends produce identical output (enforced by EncodingBackend::Both).
/// This verifies strip encoder parity without depending on specific hashes.
#[test]
fn test_frymire_backend_parity() {
    let (rgb, width, height) = load_frymire();

    // Test all configs that support strip encoding (baseline and progressive, including XYB)
    let strip_configs = test_configs()
        .into_iter()
        .filter(|c| c.mode == JpegMode::Baseline || c.mode == JpegMode::Progressive)
        .collect::<Vec<_>>();

    for config in &strip_configs {
        for &quality in &[50u8, 90] {
            // Use Both backend - will error if outputs differ
            let _jpeg = Encoder::new()
                .width(width)
                .height(height)
                .pixel_format(PixelFormat::Rgb)
                .jpegli_quality(Quality::from_quality(quality as f32))
                .mode(config.mode)
                .subsampling(config.subsampling)
                .optimize_huffman(config.optimize_huffman)
                .chroma_downsampling(config.chroma_downsampling)
                .use_xyb(config.use_xyb)
                .encoding_backend(EncodingBackend::Both)
                .encode(&rgb)
                .unwrap_or_else(|e| panic!("{} Q{}: backend mismatch: {}", config.name, quality, e));
        }
    }
}

