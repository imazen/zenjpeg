// Check which AC symbols are in the standard Huffman table
// and which ones we're trying to use

fn main() {
    // Standard AC luminance values from huffman.rs
    let std_ac_luminance_values: [u8; 162] = [
        0x01, 0x02, 0x03, 0x00, 0x04, 0x11, 0x05, 0x12, 0x21, 0x31, 0x41, 0x06, 0x13, 0x51, 0x61,
        0x07, 0x22, 0x71, 0x14, 0x32, 0x81, 0x91, 0xa1, 0x08, 0x23, 0x42, 0xb1, 0xc1, 0x15, 0x52,
        0xd1, 0xf0, 0x24, 0x33, 0x62, 0x72, 0x82, 0x09, 0x0a, 0x16, 0x17, 0x18, 0x19, 0x1a, 0x25,
        0x26, 0x27, 0x28, 0x29, 0x2a, 0x34, 0x35, 0x36, 0x37, 0x38, 0x39, 0x3a, 0x43, 0x44, 0x45,
        0x46, 0x47, 0x48, 0x49, 0x4a, 0x53, 0x54, 0x55, 0x56, 0x57, 0x58, 0x59, 0x5a, 0x63, 0x64,
        0x65, 0x66, 0x67, 0x68, 0x69, 0x6a, 0x73, 0x74, 0x75, 0x76, 0x77, 0x78, 0x79, 0x7a, 0x83,
        0x84, 0x85, 0x86, 0x87, 0x88, 0x89, 0x8a, 0x92, 0x93, 0x94, 0x95, 0x96, 0x97, 0x98, 0x99,
        0x9a, 0xa2, 0xa3, 0xa4, 0xa5, 0xa6, 0xa7, 0xa8, 0xa9, 0xaa, 0xb2, 0xb3, 0xb4, 0xb5, 0xb6,
        0xb7, 0xb8, 0xb9, 0xba, 0xc2, 0xc3, 0xc4, 0xc5, 0xc6, 0xc7, 0xc8, 0xc9, 0xca, 0xd2, 0xd3,
        0xd4, 0xd5, 0xd6, 0xd7, 0xd8, 0xd9, 0xda, 0xe1, 0xe2, 0xe3, 0xe4, 0xe5, 0xe6, 0xe7, 0xe8,
        0xe9, 0xea, 0xf1, 0xf2, 0xf3, 0xf4, 0xf5, 0xf6, 0xf7, 0xf8, 0xf9, 0xfa,
    ];

    // For AC refinement scan, we use symbols with size=1 only (plus EOB=0x00 and ZRL=0xF0)
    // Symbol format: (run << 4) | size
    // For refinement: size is always 1, so symbols are: 0x01, 0x11, 0x21, ... 0xF1

    println!("Symbols needed for AC refinement:");
    println!("  0x00 (EOB)");
    println!("  0xF0 (ZRL)");
    for run in 0..=15 {
        let symbol = (run << 4) | 1;
        println!("  0x{:02X} (run={}, size=1)", symbol, run);
    }

    println!("\nChecking if all refinement symbols are in standard table:");

    // EOB
    let eob_present = std_ac_luminance_values.contains(&0x00);
    println!(
        "  0x00 (EOB): {}",
        if eob_present { "PRESENT" } else { "MISSING" }
    );

    // ZRL
    let zrl_present = std_ac_luminance_values.contains(&0xF0);
    println!(
        "  0xF0 (ZRL): {}",
        if zrl_present { "PRESENT" } else { "MISSING" }
    );

    // Run/size=1 symbols
    for run in 0..=15 {
        let symbol = (run << 4) | 1;
        let present = std_ac_luminance_values.contains(&symbol);
        println!(
            "  0x{:02X} (run={}, size=1): {}",
            symbol,
            run,
            if present { "PRESENT" } else { "MISSING" }
        );
    }

    // EOB run symbols (0x10, 0x20, 0x30, ...)
    // These have size=0 and run > 0, which encodes an EOB run
    println!("\nEOB run symbols (for batching multiple EOB blocks):");
    for run in 1..=14 {
        // 0 is handled as single EOB (0x00), 15 is ZRL
        let symbol = run << 4; // size=0
        let present = std_ac_luminance_values.contains(&symbol);
        println!(
            "  0x{:02X} (eob_run={}): {}",
            symbol,
            run,
            if present { "PRESENT" } else { "MISSING" }
        );
    }

    // Actually, let's look at all symbols with size=0 (special meaning)
    println!("\nAll size=0 symbols in standard table:");
    for &sym in &std_ac_luminance_values {
        if (sym & 0x0F) == 0 {
            let run = sym >> 4;
            let meaning = match run {
                0 => "EOB (single)",
                15 => "ZRL (16 zeros)",
                n => &format!("EOB run {} (2^{} + extra blocks)", n, n),
            };
            println!("  0x{:02X}: run={}, {}", sym, run, meaning);
        }
    }
}
