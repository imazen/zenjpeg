/// Within-cell slope `d(achieved-vs-original) / d(generation-loss-vs-
/// source)`, fit on the n=50 val data (corr 0.80). Used by the closed
/// loop to convert a measured generation-loss deviation into an
/// achieved-quality correction.
pub const GEXP_SLOPE: f32 = 1.1;

/// Expected generation loss (vs source) for a cell, or `None` if the
/// encoder has no GEXP table. Spirals out of NaN cells like [`lookup`].
pub fn gexp_lookup(encoder: EncoderClass, source_est: f32, dial: f32) -> Option<f32> {
    let table = match encoder {
        EncoderClass::IjgFamily => TURBO_GEXP,
        EncoderClass::Mozjpeg | EncoderClass::ImageMagick => MOZJPEG_GEXP,
        EncoderClass::JpegliYcbcr | EncoderClass::JpegliXyb => JPEGLI_GEXP,
        _ => return None,
    };
    let si = nearest_idx(source_est, PE_SRC_BUCKETS);
    let ti = nearest_idx(dial, PE_TARGETS);
    nearest_finite(table, si, ti)
}

/// Look up `(projected_achieved, projected_size_ratio)` for an encoder ×
/// strategy × (source_estimate, target) cell. `None` if this
/// encoder/strategy has no per-encoder table (caller falls back to the
/// jpegli `data::lookup_*`).
pub fn lookup(
    encoder: EncoderClass,
    strategy: StrategyKind,
    source_est: f32,
    target: f32,
) -> Option<(f32, f32)> {
    let (ach, rat) = tables_for(encoder, strategy)?;
    let si = nearest_idx(source_est, PE_SRC_BUCKETS);
    let ti = nearest_idx(target, PE_TARGETS);
    let a = nearest_finite(ach, si, ti)?;
    let r = nearest_finite(rat, si, ti)?;
    Some((a, r))
}

/// Table family by encoder: libjpeg-turbo / IJG / Pillow use standard
/// IJG (Annex K) tables → TURBO_* tables. mozjpeg AND ImageMagick use
/// Robidoux tables → MOZJPEG_* tables (the Robidoux-source proxy;
/// ImageMagick itself is not yet directly swept). This grouping follows
/// the quant-table family, which governs how coefficients requantize.
/// Returns `None` for jpegli — it keeps the richer 15-image
/// `data::lookup_420/444` calibration.
fn tables_for(encoder: EncoderClass, strategy: StrategyKind) -> Option<AchievedRatioTables> {
    let _ = (JPEGLI_PRESERVE_ACHIEVED, JPEGLI_TUNED_ACHIEVED); // keep alive
    Some(match (encoder, strategy) {
        (EncoderClass::IjgFamily, StrategyKind::Preserve) => {
            (TURBO_PRESERVE_ACHIEVED, TURBO_PRESERVE_RATIO)
        }
        (EncoderClass::IjgFamily, _) => (TURBO_TUNED_ACHIEVED, TURBO_TUNED_RATIO),
        (EncoderClass::Mozjpeg | EncoderClass::ImageMagick, StrategyKind::Preserve) => {
            (MOZJPEG_PRESERVE_ACHIEVED, MOZJPEG_PRESERVE_RATIO)
        }
        (EncoderClass::Mozjpeg | EncoderClass::ImageMagick, _) => {
            (MOZJPEG_TUNED_ACHIEVED, MOZJPEG_TUNED_RATIO)
        }
        _ => return None,
    })
}

/// Inverse calibration: find the **target dial** (in zensim-A, on the
/// `PE_TARGETS` axis) that makes this strategy actually *achieve*
/// `user_target` on a source at `source_est`, plus the projected size
/// ratio at that dial. This corrects the strategy's systematic over/
/// under-shoot — feed the returned dial to `target_zensim_a_to_ijg_q`
/// so the strategy lands on `user_target` rather than the achieved
/// value at the naive dial.
///
/// Returns `(dial_zensim_a, projected_size_ratio, projected_achieved)`.
/// When `user_target` is bracketed by the row, `projected_achieved ==
/// user_target` (we dialed to hit it). When the target is below the
/// achievable floor (gentlest dial over-delivers), `projected_achieved`
/// is that floor (> target, safe); when above the ceiling (coarsest dial
/// can't reach it), it's the ceiling (< target).
pub fn invert_dial(
    encoder: EncoderClass,
    strategy: StrategyKind,
    source_est: f32,
    user_target: f32,
) -> Option<(f32, f32, f32)> {
    let (ach, rat) = tables_for(encoder, strategy)?;
    let si = nearest_idx(source_est, PE_SRC_BUCKETS);
    // Achieved as a function of dial along this source row, skipping NaN.
    let row: Vec<(f32, f32, f32)> = (0..PE_TARGETS.len())
        .filter_map(|ti| {
            let a = nearest_finite(ach, si, ti)?;
            let r = nearest_finite(rat, si, ti)?;
            Some((PE_TARGETS[ti], a, r))
        })
        .collect();
    if row.is_empty() {
        return None;
    }
    // achieved is (mostly) monotone increasing in dial. Find the dial
    // bracket where achieved crosses user_target and interpolate.
    for w in row.windows(2) {
        let (d0, a0, r0) = w[0];
        let (d1, a1, r1) = w[1];
        let (lo, hi) = if a0 <= a1 { (a0, a1) } else { (a1, a0) };
        if user_target >= lo && user_target <= hi && (a1 - a0).abs() > 1e-3 {
            let t = (user_target - a0) / (a1 - a0);
            return Some((d0 + t * (d1 - d0), r0 + t * (r1 - r0), user_target));
        }
    }
    let &(d_lo, a_lo, r_lo) = row.first().unwrap();
    let &(d_hi, a_hi, r_hi) = row.last().unwrap();
    if user_target < a_lo.min(a_hi) {
        // over-deliver floor: gentlest available, lowest achieved/file.
        if a_lo <= a_hi {
            Some((d_lo, r_lo, a_lo))
        } else {
            Some((d_hi, r_hi, a_hi))
        }
    } else {
        // can't reach: coarsest available, highest achieved.
        if a_hi >= a_lo {
            Some((d_hi, r_hi, a_hi))
        } else {
            Some((d_lo, r_lo, a_lo))
        }
    }
}

fn nearest_idx(v: f32, axis: &[f32]) -> usize {
    let mut best = 0;
    let mut bd = f32::INFINITY;
    for (i, &a) in axis.iter().enumerate() {
        let d = (v - a).abs();
        if d < bd {
            bd = d;
            best = i;
        }
    }
    best
}

/// Read `t[si][ti]`; if NaN, spiral out to the nearest covered cell.
fn nearest_finite(t: &[[f32; 6]; 6], si: usize, ti: usize) -> Option<f32> {
    if t[si][ti].is_finite() {
        return Some(t[si][ti]);
    }
    for radius in 1..6usize {
        for ds in -(radius as isize)..=(radius as isize) {
            for dt in -(radius as isize)..=(radius as isize) {
                if ds.abs() != radius as isize && dt.abs() != radius as isize {
                    continue;
                }
                let r = si as isize + ds;
                let c = ti as isize + dt;
                if (0..6).contains(&r) && (0..6).contains(&c) {
                    let v = t[r as usize][c as usize];
                    if v.is_finite() {
                        return Some(v);
                    }
                }
            }
        }
    }
    None
}
