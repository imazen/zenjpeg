// --- Expected generation-loss (vs-source) tables — Lever 4 ----------------
//
// `*_GEXP[src][tgt]` is the MEDIAN zensim-A of the recompressed output
// measured against the SOURCE jpeg (i.e. generation loss, NOT vs the
// original) for a cell at (source-estimate bucket, target/dial). This is
// the quantity the closed loop CAN measure at production time — the
// original reference is unavailable. Rows/cols share the `PE_SRC_BUCKETS`
// / `PE_TARGETS` axes.
//
// Provenance: fit 2026-05-29 from the n=50 CID22-512 end-to-end router
// validation sweeps (the `MaxIterations(1)` measured-vs-source column),
// median over dial-bearing (tuned/preserve) cells. See
// benchmarks/calibration-n50-2026-05-29.pointer.md. NaN = no recompression
// data (source ≤ target ⇒ NoOp). These are hand-fit from the val data
// rather than auto-spliced because the forced-strategy sweep runs OneShot
// and does not record vs-source; regenerating them through
// `scripts/recalibrate.sh` needs the forced sweep switched to
// `MaxIterations(1)` first (tracked follow-up).
//
// Why the closed loop uses these: within a cell, per-image deviation in
// vs-source generation loss tracks per-image deviation in achieved-vs-
// original almost 1:1 (corr 0.80, slope ≈ 1.1, 88% sign concordance on
// the n=50 val data). So `A_hat = anchor + SLOPE·(g_measured − GEXP)`
// recovers the per-image achieved estimate the bucket-median calibration
// cannot.
