//! Per-encoder, per-strategy achieved-quality + size-ratio tables,
//! measured from forced-strategy recompress-sweeps on REAL encoder
//! output (pinned libjpeg-turbo 3.1.0, mozjpeg 4.1.5, jpegli), with
//! HybridMaxCompression re-encode params.
//!
//! These replace the jpegli-only `data::lookup_420` projection for the
//! turbo/mozjpeg/jpegli encoder classes. They capture two facts the
//! single jpegli table could not:
//!   - **Preserve craters** on aggressive non-jpegli targets (large
//!     source−target gap): coefficient-domain requantization of
//!     turbo/mozjpeg tables over-quantizes (turbo src90→t50 achieves
//!     ~13, not 50).
//!   - **Tuned floors** but never craters: re-encoding decoded pixels
//!     is source-encoder-independent and well-behaved, but cannot
//!     deliver very-low targets from very-high-quality sources (the
//!     decoded pixels are already good).
//!
//! The router uses these to pick the strategy whose projected achieved
//! lands closest to (and at-or-above) the target — routing aggressive
//! non-jpegli recompression to Tuned and avoiding Preserve's cliff.
//!
//! Fit on 50 CID22-512 refs (2026-05-29 recalibration); see
//! `benchmarks/calibration-n50-2026-05-29.pointer.md` for provenance.

